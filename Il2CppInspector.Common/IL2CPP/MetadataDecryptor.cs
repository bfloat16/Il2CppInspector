using System.Buffers.Binary;
using System.Numerics;
using System.Runtime.CompilerServices;

namespace Il2CppInspector;

internal static class MetadataDecryptor
{
    private const uint EncryptedMagic = 0x214E4D46; // "FMN!"
    private const uint StandardMagic = 0xFAB11BAF;

    public static bool IsEncrypted(ReadOnlySpan<byte> data) => data.Length >= 0x28 && BinaryPrimitives.ReadUInt32LittleEndian(data) == EncryptedMagic;

    public static bool TryDecrypt(Span<byte> data)
    {
        if (data.Length < 0x28)
            return false;

        DecryptHeader(data);
        UnshuffleHeaderFields(data);
        BinaryPrimitives.WriteUInt32LittleEndian(data, StandardMagic);

        var stringLiteralOffset = BinaryPrimitives.ReadInt32LittleEndian(data.Slice(0x08));
        var stringLiteralSize = BinaryPrimitives.ReadInt32LittleEndian(data.Slice(0x0C));
        var stringLiteralDataOffset = BinaryPrimitives.ReadInt32LittleEndian(data.Slice(0x10));
        var stringLiteralDataSize = BinaryPrimitives.ReadInt32LittleEndian(data.Slice(0x14));
        var stringOffset = BinaryPrimitives.ReadInt32LittleEndian(data.Slice(0x18));
        var stringSize = BinaryPrimitives.ReadInt32LittleEndian(data.Slice(0x1C));

        if (stringOffset < 0 || stringSize < 0 || stringOffset + stringSize > data.Length)
            return false;
        if (stringLiteralOffset < 0 || stringLiteralSize < 0 || stringLiteralOffset + stringLiteralSize > data.Length)
            return false;
        if (stringLiteralDataOffset < 0 || stringLiteralDataSize < 0 || stringLiteralDataOffset + stringLiteralDataSize > data.Length)
            return false;

        DecryptStringTable(data, stringOffset, stringSize);
        DecryptStringLiteralData(data, stringLiteralOffset, stringLiteralSize, stringLiteralDataOffset);

        return true;
    }

    // ChaCha20-decrypt bytes 0x08..0x27 with custom constants
    private static void DecryptHeader(Span<byte> data)
    {
        Span<byte> keystream = stackalloc byte[64];
        ChaCha20Block(keystream, HeaderKey);

        for (var i = 0; i < 32; i++)
            data[0x08 + i] ^= keystream[i];
    }

    // Rearrange 8 header fields from shuffled order to standard order
    private static void UnshuffleHeaderFields(Span<byte> data)
    {
        var fields = data.Slice(0x08, 32);
        Span<int> shuffled = stackalloc int[8];
        for (var i = 0; i < 8; i++)
            shuffled[i] = BinaryPrimitives.ReadInt32LittleEndian(fields.Slice(i * 4));

        // shuffled[0]=EventsOff→std[6], [1]=EventsSz→std[7], [2]=LitDataSz→std[3],
        // [3]=LitOff→std[0], [4]=LitDataOff→std[2], [5]=StrOff→std[4],
        // [6]=StrSz→std[5], [7]=LitSz→std[1]
        Span<int> standard = stackalloc int[8];
        standard[0] = shuffled[3];
        standard[1] = shuffled[7];
        standard[2] = shuffled[4];
        standard[3] = shuffled[2];
        standard[4] = shuffled[5];
        standard[5] = shuffled[6];
        standard[6] = shuffled[0];
        standard[7] = shuffled[1];

        for (var i = 0; i < 8; i++)
            BinaryPrimitives.WriteInt32LittleEndian(fields.Slice(i * 4), standard[i]);
    }

    private static void DecryptStringTable(Span<byte> data, int stringOffset, int stringSize)
    {
        var idx = 0;
        while (idx < stringSize)
        {
            var absPos = stringOffset + idx;
            var r8d = unchecked((uint)((stringOffset + idx) * stringSize));
            var ki = (int)((r8d % 0x11D53 & 0xF) << 4);

            while (absPos < stringOffset + stringSize)
            {
                data[absPos] ^= StringXorTable[ki];
                if (data[absPos] == 0)
                    break;
                ki = (ki + 1) & 0xFF;
                absPos++;
            }

            var strLen = absPos - (stringOffset + idx);
            idx += strLen + 1;
        }
    }

    private static void DecryptStringLiteralData(Span<byte> data, int stringLiteralOffset, int stringLiteralSize, int stringLiteralDataOffset)
    {
        var numLiterals = stringLiteralSize / 8;
        for (var i = 0; i < numLiterals; i++)
        {
            var entryOff = stringLiteralOffset + i * 8;
            var length = (int)BinaryPrimitives.ReadUInt32LittleEndian(data.Slice(entryOff));
            var dataOff = BinaryPrimitives.ReadInt32LittleEndian(data.Slice(entryOff + 4));
            if (length == 0)
                continue;

            var ki = (int)(((unchecked((uint)(dataOff * length)) + (uint)i) & 0xF) << 4);
            var absPos = stringLiteralDataOffset + dataOff;
            for (var j = 0; j < length; j++)
            {
                data[absPos + j] ^= LiteralXorTable[ki];
                ki = (ki + 1) & 0xFF;
            }
        }
    }

    #region ChaCha20

    private static readonly uint[] ChaChaConstants = [0xA5202E99, 0xD7C2E4B2, 0x34C2418A, 0xF98AAB49];

    private static void ChaCha20Block(Span<byte> output, ReadOnlySpan<byte> key)
    {
        Span<uint> state = stackalloc uint[16];

        state[0] = ChaChaConstants[0];
        state[1] = ChaChaConstants[1];
        state[2] = ChaChaConstants[2];
        state[3] = ChaChaConstants[3];

        for (var i = 0; i < 8; i++)
            state[4 + i] = BinaryPrimitives.ReadUInt32LittleEndian(key.Slice(i * 4));

        // counter = 0 → state[12] = state[13] = 0
        // nonce = first 8 bytes of key → state[14], state[15]
        state[14] = BinaryPrimitives.ReadUInt32LittleEndian(key);
        state[15] = BinaryPrimitives.ReadUInt32LittleEndian(key.Slice(4));

        Span<uint> w = stackalloc uint[16];
        state.CopyTo(w);

        for (var i = 0; i < 10; i++)
        {
            QR(ref w[0], ref w[4], ref w[8], ref w[12]);
            QR(ref w[1], ref w[5], ref w[9], ref w[13]);
            QR(ref w[2], ref w[6], ref w[10], ref w[14]);
            QR(ref w[3], ref w[7], ref w[11], ref w[15]);
            QR(ref w[0], ref w[5], ref w[10], ref w[15]);
            QR(ref w[1], ref w[6], ref w[11], ref w[12]);
            QR(ref w[2], ref w[7], ref w[8], ref w[13]);
            QR(ref w[3], ref w[4], ref w[9], ref w[14]);
        }

        for (var i = 0; i < 16; i++)
            BinaryPrimitives.WriteUInt32LittleEndian(output.Slice(i * 4), w[i] + state[i]);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static void QR(ref uint a, ref uint b, ref uint c, ref uint d)
    {
        a += b;
        d ^= a;
        d = BitOperations.RotateLeft(d, 16);
        c += d;
        b ^= c;
        b = BitOperations.RotateLeft(b, 12);
        a += b;
        d ^= a;
        d = BitOperations.RotateLeft(d, 8);
        c += d;
        b ^= c;
        b = BitOperations.RotateLeft(b, 7);
    }

